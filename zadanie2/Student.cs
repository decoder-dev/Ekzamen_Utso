using System;

namespace StudentApp // Вы можете выбрать другое пространство имен
{
    /// <summary>
    /// Класс, представляющий студента.
    /// Содержит информацию о фамилии, имени, отчестве, курсе и специальности.
    /// </summary>
    public class Student
    {
        // Закрытые поля (члены класса)
        private string фамилия;
        private string имя;
        private string отчество;
        private int курс;
        private string специальность;

        /// <summary>
        /// Публичный конструктор по умолчанию.
        /// Инициализирует поля значениями "Не указано" или 0.
        /// </summary>
        public Student()
        {
            this.фамилия = "Не указано";
            this.имя = "Не указано";
            this.отчество = "Не указано";
            this.курс = 0;
            this.специальность = "Не указана";
        }

        /// <summary>
        /// Публичный конструктор с параметрами для инициализации всех полей.
        /// </summary>
        /// <param name="фамилия">Фамилия студента.</param>
        /// <param name="имя">Имя студента.</param>
        /// <param name="отчество">Отчество студента.</param>
        /// <param name="курс">Курс обучения.</param>
        /// <param name="специальность">Специальность студента.</param>
        public Student(string фамилия, string имя, string отчество, int курс, string специальность)
        {
            this.фамилия = фамилия;
            this.имя = имя;
            this.отчество = отчество;
            this.курс = курс;
            this.специальность = специальность;
        }

        /// <summary>
        /// Еще один публичный конструктор (пример другого конструктора).
        /// Инициализирует только фамилию, имя и курс. Остальные поля получают значения по умолчанию.
        /// </summary>
        /// <param name="фамилия">Фамилия студента.</param>
        /// <param name="имя">Имя студента.</param>
        /// <param name="курс">Курс обучения.</param>
        public Student(string фамилия, string имя, int курс)
        {
            this.фамилия = фамилия;
            this.имя = имя;
            this.отчество = "Не указано"; // Значение по умолчанию для этого конструктора
            this.курс = курс;
            this.специальность = "Не указана"; // Значение по умолчанию для этого конструктора
        }

        /// <summary>
        /// Публичный метод для отображения информации о студенте на экране.
        /// </summary>
        public void DisplayStudentInfo()
        {
            Console.WriteLine("------------------------------");
            Console.WriteLine($"Студент: {фамилия} {имя} {отчество}");
            Console.WriteLine($"Курс: {курс}");
            Console.WriteLine($"Специальность: {специальность}");
            Console.WriteLine("------------------------------");
        }
    }
}